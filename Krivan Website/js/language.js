class KrivanLanguageManager {
  constructor() {
    this.currentLang = localStorage.getItem('krivan_lang') || 'en';
    this.init();
  }

  init() {
    document.addEventListener('DOMContentLoaded', () => {
      this.applyLanguage(this.currentLang);
      this.bindSwitcherEvents();
    });
  }

  setLanguage(lang) {
    if (!KrivanTranslations[lang]) return;
    this.currentLang = lang;
    localStorage.setItem('krivan_lang', lang);
    this.applyLanguage(lang);
  }

  applyLanguage(lang) {
    const t = KrivanTranslations[lang] || KrivanTranslations.en;
    
    // Update all elements with data-i18n attribute
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (t[key]) {
        el.textContent = t[key];
      }
    });

    // Update active state in language selector UI
    document.querySelectorAll('.lang-btn').forEach(btn => {
      if (btn.getAttribute('data-lang') === lang) {
        btn.classList.add('active');
      } else {
        btn.classList.remove('active');
      }
    });
    
    // Dispatch custom event for dynamic components (like products.js)
    window.dispatchEvent(new CustomEvent('krivanLanguageChanged', { detail: { lang } }));
  }

  bindSwitcherEvents() {
    document.addEventListener('click', (e) => {
      const btn = e.target.closest('.lang-btn');
      if (btn) {
        const lang = btn.getAttribute('data-lang');
        if (lang) {
          this.setLanguage(lang);
        }
      }
    });
  }
}

const langManager = new KrivanLanguageManager();
